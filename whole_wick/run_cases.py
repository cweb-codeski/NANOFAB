"""Run the whole-wick cases under every comparison heat map and write Stage C-F reports.

    python whole_wick/run_cases.py [--heat-maps uniform_50 gaussian_hotspot] [--out results/cases]

Outputs per heat map: comparison.csv, per-case field maps (PNG), per-cell CSVs, and a summary
markdown file with electrowetting effect, dryout, mass/energy audits and input provenance.
"""

from __future__ import annotations

import argparse
import sys
import warnings
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from nanofab.provenance import REPORT_CATEGORY  # noqa: E402
from nanofab.whole_wick import load_case_set  # noqa: E402
from nanofab.whole_wick.cases import cell_table, run_case  # noqa: E402
from nanofab.whole_wick.model import ELECTRICAL_POWER_STATUS  # noqa: E402
from nanofab.whole_wick.properties import table_summary  # noqa: E402
from nanofab.whole_wick.report import (  # noqa: E402
    markdown_table,
    plot_result,
    provenance_rows,
    write_columns,
    write_csv,
)

EW_COLUMNS = [
    ("case", "case", ""),
    ("actuation", "actuation", ""),
    ("V_applied_V", "V [V]", ".1f"),
    ("actuated_area_fraction", "actuated area", ".2f"),
    ("theta_0_deg", "θ_0 [°]", ".2f"),
    ("theta_V_deg", "θ_V [°]", ".2f"),
    ("dtheta_deg", "Δθ [°]", "+.2f"),
    ("Pc_max0_Pa", "Pc_max(0) [Pa]", ".0f"),
    ("Pc_maxV_Pa", "Pc_max(V) [Pa]", ".0f"),
    ("dPc_max_pct", "ΔPc_max [%]", "+.2f"),
    ("dielectric_field_V_um", "V/t [V/µm]", ".1f"),
    ("ew_saturated", "cos θ capped", ""),
    ("electrical_power", "electrical power", ""),
]
DRYOUT_COLUMNS = [
    ("case", "case", ""),
    ("actuation", "actuation", ""),
    ("dryout_mean_W_cm2", "dryout mean q'' [W/cm²]", ".2f"),
    ("dryout_peak_W_cm2", "dryout peak q'' [W/cm²]", ".1f"),
    ("dQ_dryout_pct", "Δ dryout vs passive [%]", "+.2f"),
    ("first_dry_x_mm", "first dry x [mm]", ".2f"),
    ("first_dry_y_mm", "first dry y [mm]", ".2f"),
    ("first_dry_actuated", "first dry cell actuated", ""),
    ("required_dp_at_dryout_Pa", "required Δp there [Pa]", ".0f"),
    ("Pc_maxV_at_dryout_Pa", "Pc_max(V) there [Pa]", ".0f"),
    ("T_max_C", "T_max at nominal [°C]", ".2f"),
    ("Q_evap_W", "Q_evap at nominal [W]", ".2f"),
    ("mass_rel_residual", "mass residual", ".1e"),
    ("energy_rel_residual", "energy residual", ".1e"),
    ("extrapolation_events", "extrap. events", "d"),
]


def run(heat_maps: list[str] | None, out: Path) -> None:
    cs = load_case_set()
    heat_maps = heat_maps or cs.cases.tree["comparison"]["heat_maps"]
    ref_name = cs.cases.tree["comparison"]["reference_case"]
    md = [
        "# Whole-wick case comparison (electrowetting)",
        "",
        "Generated by `whole_wick/run_cases.py`. **Not validated** (see `validation/VALIDATION_REPORT.md`).",
        "Electrical assistance is electrowetting only: voltage changes the receding contact angle and",
        "therefore Pc_max(V) = 2γ cos θ_V / r_eff. It does not change h_e, K or the heat input. Dryout",
        "compares the required p_v − p_l with Pc_max(V) cell by cell. h_e(Pc) is an ASSUMED placeholder",
        "(W18). Lippmann-Young parameters ε_r and θ_sat are ASSUMED (`docs/whole_wick_assumptions.md`).",
        "",
        f"**Electrical power: {ELECTRICAL_POWER_STATUS}.** No power, energy or efficiency claim is",
        "made. Only the applied voltage is reported.",
        "",
    ]
    for hm in heat_maps:
        with warnings.catch_warnings(record=True) as caught:
            warnings.simplefilter("always")
            summaries = {c: run_case(cs, c, hm) for c in [ref_name] + [c for c in cs.case_names if c != ref_name]}
        ref = summaries[ref_name]
        rows = [summaries[c].row(ref) for c in cs.case_names]
        d = out / hm
        write_csv(rows, d / "comparison.csv")
        md += [f"## Heat map `{hm}`", "", "Electrowetting effect (mean over actuated cells):", "",
               markdown_table(rows, EW_COLUMNS), "", "Dryout and conservation:", "",
               markdown_table(rows, DRYOUT_COLUMNS), ""]
        for case, s in summaries.items():
            plot_result(s.nominal, d / f"{case}_nominal.png", f"{case} / {hm} / nominal load")
            plot_result(s.dryout.result, d / f"{case}_dryout.png", f"{case} / {hm} / dryout onset")
            write_columns(cell_table(s.nominal), d / f"{case}_cells_nominal.csv")
            n = s.nominal
            md += [
                f"### `{case}` (actuation: {n.model.actuation})",
                "",
                "Stage C, mass balance at nominal load:",
                "```text", *n.darcy.mass.lines(), "```",
                "Stage D, energy balance at nominal load:",
                "```text", *n.thermal.energy.lines(),
                f"max temperature      {n.thermal.T_max - 273.15:.3f} C at (x, y) = "
                f"({n.thermal.T_max_location[0] * 1e3:.2f}, {n.thermal.T_max_location[1] * 1e3:.2f}) mm",
                f"max local q''_evap   {n.thermal.q_evap.max() / 1e4:.2f} W/cm^2",
                f"Picard iterations    {n.iterations} (converged: {n.converged})",
                "```",
                "Stage E, dryout onset (required p_v − p_l vs Pc_max(V)):",
                "```text", *s.dryout.lines(), "```",
                f"![{case}](./{hm}/{case}_dryout.png)",
                "",
            ]
        if caught:
            md += ["Warnings raised during this heat map:", "", "```text", *sorted({str(w.message) for w in caught}), "```", ""]

    md += ["## Property sources", "", markdown_table(table_summary(cs.cell_types, cs.gamma.value), [
        ("cell_type", "cell type", ""), ("property", "property", ""), ("unit", "unit", ""),
        ("min", "min", ".4g"), ("max", "max", ".4g"), ("axes", "axes", ""),
        ("category", "category", ""), ("source_location", "source", "")]), ""]
    prov = provenance_rows(cs.registry)
    write_csv(prov, out / "parameter_provenance.csv")
    counts: dict[str, int] = {}
    for r in prov:
        counts[r["category"]] = counts.get(r["category"], 0) + 1
    md += ["## Input provenance", "", "Full list: `parameter_provenance.csv`.", ""]
    md += [f"- {cat}: {counts.get(cat, 0)} inputs" for cat in dict.fromkeys(REPORT_CATEGORY.values())]
    (out / "SUMMARY.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"wrote {out / 'SUMMARY.md'}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--heat-maps", nargs="*")
    ap.add_argument("--out", type=Path, default=ROOT / "results" / "cases")
    a = ap.parse_args()
    run(a.heat_maps, a.out)
