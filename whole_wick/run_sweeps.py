"""Parameter sweeps on the whole-wick model (Stage F).

    python whole_wick/run_sweeps.py [--out results/sweeps]

Electrowetting sweeps: voltage (global, selective), zero-voltage angle theta_0, saturation angle,
dielectric thickness, selective threshold. Model-form sweeps: heat load (monotonicity), K(Pc)
reduction, h_e level, graded-zone pitch. The swept inputs are the ASSUMED ones that most affect
the outputs (rule 7, docs/SOURCE_AUTHORITY.md). Electrical power is unresolved and not reported.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from nanofab.whole_wick import heat_load_sweep, load_case_set, parameter_sweep  # noqa: E402
from nanofab.whole_wick.report import markdown_table, write_csv  # noqa: E402

RECIPE = "cells.property_recipes.analytical_flat_placeholder_he"
BASE = "cells.cell_types.si_d10_l30_h25"
COATING = "cells.dielectric_coatings.sio2_1um"
COLS = [
    ("value", "value", ""), ("V_applied_V", "V [V]", ".1f"), ("actuated_area_fraction", "actuated area", ".2f"),
    ("theta_0_deg", "θ_0 [°]", ".1f"), ("theta_V_deg", "θ_V [°]", ".2f"), ("dPc_max_pct", "ΔPc_max [%]", "+.2f"),
    ("ew_saturated", "cos θ capped", ""), ("dryout_mean_W_cm2", "dryout q'' [W/cm²]", ".2f"),
    ("first_dry_x_mm", "first dry x [mm]", ".2f"), ("T_max_C", "T_max [°C]", ".2f"),
]


def theta_leaf(deg: float) -> dict:
    return {"value": deg, "unit": "deg", "provenance": "USER_PROVIDED", "source": None, "source_location": "sweep"}


def main(out: Path) -> None:
    md = ["# Whole-wick parameter sweeps", "",
          "Generated by `whole_wick/run_sweeps.py`. Not validated. Electrical power is unresolved; only V is reported.", ""]
    cs = load_case_set()

    rows = heat_load_sweep(cs.build("passive_uniform", "uniform_50"), [0.25, 0.5, 1.0, 1.5, 1.9, 2.0, 2.1])
    write_csv(rows, out / "heat_load_passive_uniform.csv")
    md += ["## Heat load, passive uniform, uniform map", "", markdown_table(rows, [
        ("mean_heat_flux_W_cm2", "q'' [W/cm²]", ".1f"), ("T_max_C", "T_max [°C]", ".3f"),
        ("max_pressure_ratio", "max required Δp / Pc_max", ".3f"), ("min_pressure_margin_Pa", "min margin [Pa]", ".0f"),
        ("Q_evap_W", "Q_evap [W]", ".2f"), ("any_dry", "dry cells", "")]), ""]

    high_v = {"cases.voltage_maps.global.V.value": 50}
    sweeps = [
        ("Voltage, global actuation (V)", "cases.voltage_maps.global.V.value", [0, 2.5, 5, 7.5, 10, 11, 12.5, 20, 50],
         "global_ew", "uniform_50", None),
        ("Voltage, selective actuation (V)", "cases.voltage_maps.selective.V.value", [0, 5, 10, 20],
         "selective_ew", "uniform_50", None),
        ("θ_0, passive (deg)", f"{BASE}.theta_0", [theta_leaf(t) for t in (5, 15, 30, 45, 60)],
         "passive_uniform", "uniform_50", None),
        ("θ_0, global actuation at 50 V (deg)", f"{BASE}.theta_0", [theta_leaf(t) for t in (5, 15, 30, 45, 60)],
         "global_ew", "uniform_50", high_v),
        ("Saturation angle θ_sat, global at 50 V (deg; ASSUMED, EW2)", f"{COATING}.saturation_angle.value", [0, 5, 10, 15, 30],
         "global_ew", "uniform_50", high_v),
        ("Dielectric thickness at 10 V (um)", f"{COATING}.t_dielectric.value", [0.25, 0.5, 1.0, 2.0, 5.0],
         "global_ew", "uniform_50", None),
        ("Selective threshold (required Δp / Pc_max(0))", "cases.voltage_maps.selective.threshold.value",
         [0.3, 0.5, 0.7, 0.8, 0.9], "selective_ew", "gaussian_hotspot", None),
        ("K reduction at Pc_max (ASSUMED, W3)", f"{RECIPE}.K",
         [{"method": "analytical_flat"}] + [
             {"method": "analytical_curvature", "reduction_at_pc_max": {"value": a, "unit": "-", "provenance": "ASSUMED",
                                                                       "source": None, "source_location": "sweep"}}
             for a in (0.1, 0.2, 0.37, 0.5)], "passive_uniform", "uniform_50", None),
        ("h_e level, kW/m²K (ASSUMED, W18)", f"{RECIPE}.h_e.h_e_at_zero_pc.value", [30, 60, 90, 120],
         "passive_uniform", "gaussian_hotspot", None),
        ("Graded dense-zone pitch (um)", "cells.cell_types.si_d10_l22_h25.pillar_pitch.value", [18, 20, 22, 26, 30],
         "passive_graded", "uniform_50", None),
    ]
    for title, path, values, case, hm, extra in sweeps:
        rows = parameter_sweep(path, values, case, hm, extra=extra)
        for r in rows:
            v = r["value"]
            if isinstance(v, dict):
                r["value"] = v.get("value", v.get("reduction_at_pc_max", {}).get("value", 0.0))
        slug = "_".join(p for p in path.split(".")[-2:] if p != "value")
        write_csv(rows, out / f"{case}_{slug}.csv")
        md += [f"## {title}: `{case}` / `{hm}`", "", markdown_table(rows, COLS), ""]
    (out / "SWEEPS.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"wrote {out / 'SWEEPS.md'}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=ROOT / "results" / "sweeps")
    main(ap.parse_args().out)
